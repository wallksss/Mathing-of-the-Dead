"""Generates lib/game/engine/unsolvable_plates.dart.

Exhaustively searches, for every plate 0000-9999, an equality using only the
operators of each level (same rules as the game: digits in order, no
concatenation, exact division except on Easy). Run from the project root:

    python tool/gen_unsolvable_plates.py

The search bounds intermediate values (|x| <= 1e7, factorial up to 10!,
exponent up to 20), so a plate listed as unsolvable could in theory need a
huger intermediate value; every plate NOT listed has a verified solution.
"""
from fractions import Fraction as F
from functools import lru_cache
import math, itertools, sys

LIM = 10**7
def unary(vals, level):
    out=set(vals)
    for _ in range(3):
        new=set()
        for v in out:
            new.add(-v); new.add(abs(v))
            if level in('easy','inter','adv'):
                # non-integer arguments are truncated, like the game: (√8)! = 2!
                if 0<=v<=10: new.add(F(math.factorial(math.floor(v))))
                if v>=0:
                    r=math.isqrt(int(v)) if v.denominator==1 else None
                    if r is not None and r*r==v: new.add(F(r))
                    # (√v)! with an inexact root: the factorial truncates it.
                    if v>=0:
                        r=math.isqrt(math.floor(v))
                        if r<=10: new.add(F(math.factorial(r)))
            if level in('easy','inter') and v.denominator==1:
                c=round(abs(v)**(1/3)) if abs(v)<1e18 else None
                if c is not None and c**3==abs(v): new.add(F(c if v>=0 else -c))
                if v>=0:
                    c=round(float(v)**(1/3))
                    while c**3>v: c-=1
                    while (c+1)**3<=v: c+=1
                    if c<=10: new.add(F(math.factorial(c)))  # (∛v)!
            if level=='easy': new.add(F(math.floor(v))); new.add(F(math.ceil(v)))
        new={x for x in new if abs(x)<=LIM}
        if new<=out: break
        out|=new
    return out

def combine(A,B,level):
    out=set()
    for a in A:
        for b in B:
            out.add(a+b); out.add(a-b); out.add(a*b)
            if b!=0:
                q=a/b
                if level=='easy' or q.denominator==1: out.add(q)
            if level in('easy','inter') and b.denominator==1 and abs(b)<=20 and a!=0:
                try:
                    p=a**int(b)
                    if abs(p)<=LIM and (level=='easy' or p.denominator==1): out.add(p)
                except ZeroDivisionError: pass
    return {x for x in out if abs(x)<=LIM}

def solvable(d, level):
    @lru_cache(None)
    def R(i,j):
        if j-i==1: return frozenset(unary({F(d[i])},level))
        s=set()
        for k in range(i+1,j): s|=combine(R(i,k),R(k,j),level)
        return frozenset(unary(s,level))
    return any(R(0,k)&R(k,4) for k in (1,2,3))

LEVELS = [('hard', 'hard'), ('adv', 'advanced'), ('inter', 'intermediate'), ('easy', 'easy')]


def main():
    # Ops of each level are a superset of the next harder one, so only plates
    # unsolvable at the harder level need to be checked again.
    remaining = [f"{n:04d}" for n in range(10000)]
    result = {}
    for key, name in LEVELS:
        remaining = [p for p in remaining
                     if not solvable(tuple(int(c) for c in p), key)]
        result[name] = remaining
        print(name, len(remaining))
    out = ["// GENERATED by tool/gen_unsolvable_plates.py - do not edit.",
           "// Plates with no equality using the operators of each level.",
           "",
           "import 'difficulty.dart';",
           ""]
    names = {'easy': 'easy', 'intermediate': 'intermediate',
             'advanced': 'advanced', 'hard': 'hard'}
    for name in names:
        codes = ''.join(result[name])
        chunks = [codes[i:i + 72] for i in range(0, len(codes), 72)] or ['']
        body = '\n'.join(f"    '{c}'" for c in chunks)
        out.append(f"const String _{name} =\n{body};")
        out.append('')
    out.append('''Set<String> _decode(String s) => {
  for (var i = 0; i + 4 <= s.length; i += 4) s.substring(i, i + 4),
};

final Map<Difficulty, Set<String>> _cache = {};

/// Plates that have no solution at [level]; they are never dealt.
Set<String> unsolvablePlates(Difficulty level) =>
    _cache[level] ??= _decode(switch (level) {
      Difficulty.easy => _easy,
      Difficulty.intermediate => _intermediate,
      Difficulty.advanced => _advanced,
      Difficulty.hard => _hard,
    });''')
    with open('lib/game/engine/unsolvable_plates.dart', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
